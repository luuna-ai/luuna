//! Markdown and TypeScript rendering, byte compatible with renderMarkdown.
use super::{unicode_data, yaml_value::Node, YamlValue};
use crate::{Beacon, BeaconError, Prompt};
use std::sync::Arc;
/// Render a resolved prompt. This function deliberately does not select a pin.
pub fn render_markdown(prompt: &Prompt) -> String {
    let sections = prompt.sections.as_deref().unwrap_or(&[]);
    let mut body = if sections.len() == 1 {
        sections[0].body.clone()
    } else {
        sections
            .iter()
            .map(|s| format!("## {}\n\n{}", s.name, s.body))
            .collect::<Vec<_>>()
            .join("\n\n")
    };
    body.push('\n');
    if prompt.emit_as.ends_with(".ts") {
        let name: String = prompt
            .name
            .replace('-', "_")
            .chars()
            .map(|c| {
                unicode_data::UPPER
                    .binary_search_by_key(&(c as u32), |(c, _)| *c)
                    .ok()
                    .and_then(|i| char::from_u32(unicode_data::UPPER[i].1))
                    .unwrap_or(c)
            })
            .collect();
        let body = body
            .replace('\\', "\\\\")
            .replace('`', "\\`")
            .replace("${", "\\${");
        let description = if prompt.description.is_empty() {
            String::new()
        } else {
            format!("// {}\n", prompt.description)
        };
        return format!("// Auto-generated by Luuna Beacon — do not edit manually\n// Prompt: {}\n{description}\nexport const {name} = `{body}`;\n",prompt.name);
    }
    let mut value = YamlValue::null();
    value.nodes[0] = Node::Map(Vec::new());
    let mut fields = std::collections::BTreeMap::new();
    fields.insert(
        "name".to_owned(),
        YamlValue::from_json(&serde_json::Value::String(prompt.name.clone())),
    );
    if !prompt.description.is_empty() {
        fields.insert(
            "description".into(),
            YamlValue::from_json(&serde_json::Value::String(prompt.description.clone())),
        );
    }
    for (key, v) in &prompt.frontmatter {
        fields.insert(key.clone(), YamlValue::from_json(v));
    }
    let mut pairs = Vec::new();
    for (key, v) in fields {
        let k = value.push(Node::String(Arc::from(key.as_bytes())));
        let v = value.append(&v);
        pairs.push((k, v))
    }
    let len = pairs.len();
    value.nodes[0] = Node::Map(pairs);
    if len > 1 || !prompt.name.is_empty() {
        format!("---\n{}---\n{body}", value.to_yaml())
    } else {
        body
    }
}
impl Beacon {
    pub fn render_text(&self, reference: &str) -> Result<String, BeaconError> {
        self.migrate_legacy()?;
        Ok(render_markdown(&self.render(reference)?.prompt))
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::Section;
    fn prompt() -> Prompt {
        Prompt {
            name: "p".into(),
            sections: Some(vec![Section {
                name: "main".into(),
                body: "text".into(),
                required: None,
            }]),
            ..Prompt::default()
        }
    }
    #[test]
    fn single_section_has_no_heading() {
        assert_eq!(render_markdown(&prompt()), "---\nname: p\n---\ntext\n")
    }
    #[test]
    fn multiple_sections_keep_headings() {
        let mut p = prompt();
        p.sections.as_mut().unwrap().push(Section {
            name: "other".into(),
            body: "next".into(),
            required: None,
        });
        assert_eq!(
            render_markdown(&p),
            "---\nname: p\n---\n## main\n\ntext\n\n## other\n\nnext\n"
        )
    }
    #[test]
    fn empty_name_omits_single_name_frontmatter() {
        let mut p = prompt();
        p.name.clear();
        assert_eq!(render_markdown(&p), "text\n")
    }
    #[test]
    fn custom_frontmatter_overrides_name() {
        let mut p = prompt();
        p.frontmatter
            .insert("name".into(), serde_json::json!("override").into());
        assert!(render_markdown(&p).starts_with("---\nname: override\n---\n"))
    }
    #[test]
    fn typescript_uses_simple_unicode_uppercase() {
        let mut p = prompt();
        p.name = "ß-hello".into();
        p.emit_as = "out.ts".into();
        assert!(render_markdown(&p).contains("export const ß_HELLO = `text\n`;"))
    }
}
